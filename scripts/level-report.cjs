// Merge the per-slice JSON written by `npm run verify:levels` into docs/LEVELS.md.
const fs = require('fs')
const path = require('path')

const dir = '.level-report'
if (!fs.existsSync(dir)) {
  console.error('No .level-report directory. Run the verifier first.')
  process.exit(1)
}
const rows = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .flatMap((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')))
rows.sort((a, b) => a.level - b.level)

const count = (key) => {
  const m = new Map()
  for (const r of rows) m.set(r[key], (m.get(r[key]) ?? 0) + 1)
  return m
}
const table = (title, m) =>
  `### ${title}\n\n| value | levels |\n| --- | --- |\n${[...m].sort((a, b) => String(a[0]).localeCompare(String(b[0]))).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}\n`

const ms = rows.map((r) => r.ms).sort((a, b) => a - b)
const q = (p) => ms[Math.min(ms.length - 1, Math.floor(ms.length * p))]
const invalid = rows.filter((r) => !r.valid)
const fallbacks = rows.filter((r) => r.fallback)
const noClub = rows.filter((r) => !r.hasClubhouse)
const templates = new Set(rows.map((r) => r.template))

const md = `# Level report

Generated by \`npm run verify:levels\` (every level is generated and route-validated).

- Levels checked: **${rows.length}**
- Invalid levels: **${invalid.length}**${invalid.length ? ` (${invalid.slice(0, 20).map((r) => r.level).join(', ')}${invalid.length > 20 ? ', ...' : ''})` : ''}
- Levels that used the fallback hole: **${fallbacks.length}** (${((fallbacks.length / rows.length) * 100).toFixed(2)}%)
- Distinct hole types used: **${templates.size}**
- Levels with a clubhouse placed: **${rows.length - noClub.length}** (${noClub.length} without)
- Levels with moving obstacles: **${rows.filter((r) => r.movers > 0).length}**
- Levels with ice: **${rows.filter((r) => r.ice > 0).length}**, puddles: **${rows.filter((r) => r.puddles > 0).length}**, wind: **${rows.filter((r) => r.wind > 0).length}**
- Generation time per level: median ${q(0.5)} ms, p95 ${q(0.95)} ms, max ${ms[ms.length - 1]} ms

${table('By theme', count('theme'))}
${table('By difficulty tier', count('tier'))}
${table('By par', count('par'))}
`
fs.mkdirSync('docs', { recursive: true })
fs.writeFileSync('docs/LEVELS.md', md)
console.log(md)
